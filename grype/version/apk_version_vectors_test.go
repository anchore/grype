func TestApkVersion_Invalid(t *testing.T) {
	for _, raw := range []string{
		"not-valid-apk-format",
		"1.2.3-1",   // a revision must be written as "-r1"
		"1.0.0_x1",  // unknown suffix
		"1.0.0B-r1", // uppercase letter
		"1.2.3-rx",  // revision without a number
	} {
		t.Run(raw, func(t *testing.T) {
			_, err := newApkVersion(raw)
			require.Error(t, err)
			assert.Contains(t, err.Error(), "invalid version")
		})
	}
}
